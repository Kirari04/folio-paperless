/** Localizes only Folio-owned diagnostics. Unknown server/provider content is preserved verbatim. */
export function presentRuntimeMessage(message: string) {
  const key = folioDiagnosticKeys[message];
  if (key) return translateRuntime(key);
  for (const diagnostic of dynamicFolioDiagnostics) {
    const match = message.match(diagnostic.pattern);
    if (match) return translateRuntime(diagnostic.key, diagnostic.values(match));
  }
  return message;
}

export function presentRuntimeError(error: unknown, fallback: string) {
  return error instanceof Error ? presentRuntimeMessage(error.message) : fallback;
}
